/**
 * Communes de référence d'un département, triées par population décroissante.
 * @param {string} deptCode — code département (ex : "13", "971")
 * @returns {Array<{nom,cp,dept,lat,lng,pop}>}
 */
export function getCommunesByDept(deptCode) {
  return COMMUNES_REFERENCE
    .filter((c) => c.dept === String(deptCode))
    .sort((a, b) => (b.pop || 0) - (a.pop || 0));
}